  var current = 'en';

  function detect() {
    var l = (navigator.language || 'en').toLowerCase();
    return l.indexOf('zh') === 0 ? 'zh-TW' : 'en';
  }

  function setLang(lang) { current = tables[lang] ? lang : 'en'; }

  function t(key, vars) {
    var s = tables[current][key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] == null ? m : String(vars[k]); });
  }

  Tab.i18n = { t: t, setLang: setLang, detect: detect, lang: function () { return current; } };
